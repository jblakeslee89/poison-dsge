function shock_variance_contribution(model, shk, var; params, periods=80, scale=1.0)
    irf = get_irf(model, parameters = params, periods = periods)
    series = [irf(var, p, shk) * scale for p in 1:periods]
    return sum(series .^ 2)
end

function welfare_loss(model; params, attack_on::Bool, λ=0.5, periods=80)
    σ_att_val = attack_on ? 1.0 : 0.0
    full_params = vcat(params, [:σ_att => σ_att_val])
    var_pi = sum(shock_variance_contribution(model, shk, :π;
                    params=full_params, periods=periods, scale=4.0)
                 for shk in [:ε_rn, :ε_ν, :ε_att])
    var_ygap = sum(shock_variance_contribution(model, shk, :ygap;
                    params=full_params, periods=periods)
                   for shk in [:ε_rn, :ε_ν, :ε_att])
    return (loss = var_pi + λ * var_ygap, var_pi = var_pi, var_ygap = var_ygap)
end

function crossover_threshold(model, κ_val::Float64, λ_val::Float64)
    base = [:κ => κ_val, :χ_p => 0.5, :h => 0.7, :ρ_i => 0.7, :ρ_p => 0.85]
    ks = 0.0:0.025:1.0
    L_off = Float64[]
    L_on  = Float64[]
    for K in ks
        params = vcat(base, [:K_gain => K])
        push!(L_off, welfare_loss(model, params=params, attack_on=false, λ=λ_val).loss)
        push!(L_on,  welfare_loss(model, params=params, attack_on=true,  λ=λ_val).loss)
    end
    idx_naive = findfirst(==(1.0), collect(ks))
    idx_best  = argmin(L_on)
    A = L_on[idx_naive];  C = L_off[idx_naive]
    B = L_on[idx_best];   D = L_off[idx_best]
    p_star = (D - C) / ((A - B) + (D - C))
    return (κ=κ_val, λ=λ_val, K_opt=ks[idx_best],
            p_crossover=p_star, L_on_naive=A, L_on_opt=B)
end

