# Three objectives:
#   (a) cumulative |Δi| (original: push rates down)
#   (b) inflation variance damage (maximize var(π))
#   (c) output-gap variance damage (maximize var(ygap))

γ_d = -log(0.5) / 0.8     # same calibration

function attacker_payoff_multi(model; A, ρ, K_gain, λ=0.5, periods=80)
    A_safe = max(A, 1e-6)
    ρ_safe = clamp(ρ, 0.0, 0.99)
    p_det = 1 - exp(-γ_d * A_safe^2 * ρ_safe)

    base = [:κ => 0.15, :χ_p => 0.5, :h => 0.7, :ρ_i => 0.7, :ρ_p => 0.85]
    params = vcat(base, [:σ_att => A_safe, :ρ_att => ρ_safe, :K_gain => K_gain])
    irf = get_irf(model, parameters = params, periods = periods)

    # (a) cumulative |Δi|: attacker wants rates down
    cum_i = -sum(irf(:i, p, :ε_att) * 100 for p in 1:8)

    # (b) var(π) damage (sum of squared IRFs attributable to attack shock)
    var_pi_attack = sum((irf(:π, p, :ε_att) * 4)^2 for p in 1:periods)

    # (c) var(ygap) damage
    var_ygap_attack = sum(irf(:ygap, p, :ε_att)^2 for p in 1:periods)

    return (p_det = p_det,
            payoff_a = (1 - p_det) * cum_i,
            payoff_b = (1 - p_det) * var_pi_attack,
            payoff_c = (1 - p_det) * var_ygap_attack)
end

