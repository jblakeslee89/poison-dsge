# At each κ, decompose welfare loss into var(π) and var(ygap) contributions
# Under naive (K=1) and optimal (K≈0.025), with attack on and off.

function decomposed_welfare(κ_val)
    base = [:κ => κ_val, :χ_p => 0.5, :h => 0.7, :ρ_i => 0.7, :ρ_p => 0.85]
    # Find K_opt at λ=0.5 for this κ
    ks = 0.0:0.025:1.0
    L_on_vec = Float64[]
    for K in ks
        p = vcat(base, [:K_gain => K])
        push!(L_on_vec, welfare_loss(PoisonNK_Filter, params=p, attack_on=true, λ=0.5).loss)
    end
    K_opt = ks[argmin(L_on_vec)]

    results = []
    for (regime_name, K_val) in [("naive", 1.0), ("optimal", K_opt)]
        for attack_on in [false, true]
            p = vcat(base, [:K_gain => K_val])
            w = welfare_loss(PoisonNK_Filter, params=p, attack_on=attack_on, λ=0.5)
            push!(results, (κ=κ_val, regime=regime_name, K_val=K_val,
                            attack_on=attack_on,
                            var_pi=w.var_pi, var_ygap=w.var_ygap, total=w.loss))
        end
    end
    return results, K_opt
end

