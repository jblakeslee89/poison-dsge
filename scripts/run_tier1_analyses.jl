# MacroModelling has get_simulation; use it to draw from the model
# and compute empirical variances.

function stoch_welfare_se(model; params, n_draws=50, n_periods=800, λ=0.5, burn=200)
    # get_simulation returns a KeyedArray (Variables × Periods × Shocks);
    # the Shocks dimension decomposes each var's path into per-shock contributions.
    # For the total simulated path we sum across shocks.
    losses = Float64[]
    for draw in 1:n_draws
        Random.seed!(1000 + draw)
        sim = get_simulation(model, parameters = params, periods = n_periods)
        # MacroModelling get_simulation returns a 3-axis KeyedArray
        # (Variables × Periods × Shocks) where the third axis has a single
        # entry :simulate — the combined realized path, not per-shock
        # decomposition. Extract the full path and drop burn-in.
        pi_path   = collect(sim(:π,    :, :simulate))
        ygap_path = collect(sim(:ygap, :, :simulate))
        pi_tail   = pi_path[(burn+1):end] .* 4.0   # annualized pp
        ygap_tail = ygap_path[(burn+1):end]
        var_pi   = sum(x^2 for x in pi_tail)   / length(pi_tail)
        var_ygap = sum(x^2 for x in ygap_tail) / length(ygap_tail)
        push!(losses, var_pi + λ * var_ygap)
    end
    m = sum(losses) / length(losses)
    return (mean = m,
            se = sqrt(sum((l - m)^2 for l in losses) /
                      (length(losses) * (length(losses) - 1))),
            n = length(losses))
end

