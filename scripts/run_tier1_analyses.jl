# Simplified univariate signal-extraction: Fed observes
#   s_t = g_t + e_t
# where g_t ~ AR(1)(ρ_g, σ²_g,shock) is the true gap and
# e_t = ν_t + attack_t is the combined noise. For an AR(1) signal
# with serially-correlated observation noise, the standard
# approach is to augment the state. Here we use a simplified
# benchmark: treat g_t as AR(1) and observation noise as the
# unconditional variance of ν + attack.
#
# Steady-state Kalman for x_t = ρ·x_{t-1} + w_t,  y_t = x_t + v_t:
#   P = ρ²·(1 - K)·P + σ²_w       (Lyapunov/Riccati)
#   K = P / (P + σ²_v)
# Solving quadratic in P gives the MMSE gain K*.

function ss_kalman_gain(ρ, σ_w2, σ_v2)
    # Solve the Riccati: P satisfies
    #   P = ρ² · σ_v² · P / (P + σ_v²) + σ_w²
    # ⇒ P² + P·(σ_v²(1 - ρ²) - σ_w²) - σ_w²·σ_v² = 0
    a = 1.0
    b = σ_v2 * (1 - ρ^2) - σ_w2
    c = -σ_w2 * σ_v2
    P = (-b + sqrt(b^2 - 4a*c)) / (2a)
    K = P / (P + σ_v2)
    return (K = K, P = P)
end

